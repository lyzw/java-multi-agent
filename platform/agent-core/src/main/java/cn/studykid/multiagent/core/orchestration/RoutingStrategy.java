package cn.studykid.multiagent.core.orchestration;

/**
 * 路由策略的<b>选择策略</b>（多级 Agent v1.1 · 第十四批）。
 *
 * <p>⚠️ <b>本枚举是「本批取舍」，不是评审冻结的模型</b>：
 * 06 变更补充只规定了「ROUTER 模式按<b>固定版本</b>的路由策略选择子 Agent」，
 * 从未规定策略的<b>内容模型</b>。此处刻意选择<b>最小可扩展</b>的一档：
 * 一个策略枚举 + 一个有序目标列表，<b>不引入条件表达式 DSL</b>
 * （没有「如果 A 且 B 则 C」这类可配置判定逻辑）。
 *
 * <p>⚠️ <b>为什么不给路由策略加条件 DSL</b>：
 * 可配置的判定逻辑一旦进入配置，就带来三个必须同时解决的问题 ——
 * ① 条件的求值必须是<b>确定性</b>的（否则同一份策略两次路由结果不同，路由输出不可复核）；
 * ② 条件语言本身需要一套发布期校验（否则「写错的条件」要到运行期才暴露）；
 * ③ 条件求值失败时的语义必须冻结（fail-closed 还是跳过）。
 * 这三件事都属于「评审未决」的范围，与其本批自造一个半成品 DSL，
 * 不如先交付一个<b>语义无歧义</b>的最小模型，把扩展点留在枚举上。
 *
 * <p>⚠️ <b>策略与声明是「两层收窄」关系</b>：
 * 父 Agent 的 {@code childAgentRefs} 声明的是<b>委派拓扑</b>（允许交给谁），
 * 路由策略声明的是<b>允许的子集与选择方式</b>（在拓扑内还能交给谁、怎么选）。
 * 策略的目标集合<b>必须</b>是拓扑的子集（发布期校验）——
 * 否则「拓扑」与「策略」就有两个真相，「谁说了算」就说不清了。
 */
public enum RoutingStrategy {

    /**
     * <b>显式目标集合</b>：模型给出的候选必须落在策略声明的目标集合内，否则<b>拒绝委派</b>。
     *
     * <p>⚠️ <b>不降级</b>：候选不命中意味着「路由没能选出合法的目标」，
     * 那是一次<b>真实的路由失败</b>，不是「换一个再试试」。
     * 静默换一个目标会让父 Agent 收到一份「不是我点的那个」的结果，
     * 却毫不知情 —— 那是把路由决策偷偷挪到了服务端，且不可复核。
     */
    EXPLICIT_TARGETS,

    /**
     * <b>有序降级</b>：模型给出的候选不落在目标集合内时，
     * 按目标集合的<b>声明顺序</b>取第一个目标。
     *
     * <p>⚠️ <b>降级只作用于「选择」，不作用于「准入」</b>：
     * 降级选中的目标仍须通过「父声明包含 → 版本固定 → 逐跳授权 →
     * 深度/次数/超时/预算」的全部判定；任何一项不通过就是失败，
     * <b>不会</b>继续尝试下一个候选。理由：逐个试下去会让「一次委派」
     * 变成「一串委派」，次数与预算的上限被绕过，且失败原因会被后面的尝试掩盖。
     *
     * <p>⚠️ <b>降级目标是策略作者显式写下的</b>：它是已发布的固定版本配置对象，
     * 不是运行期推断的结果 —— 因此降级后的委派仍然可复核（MA-T05 / MA-T15）。
     */
    ORDERED_FALLBACK
}

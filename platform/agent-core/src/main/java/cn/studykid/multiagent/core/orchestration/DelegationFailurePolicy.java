package cn.studykid.multiagent.core.orchestration;

/**
 * 委派失败策略（FR-027 · 07「状态与失败语义」）。
 *
 * <p>⚠️ <b>只描述「子调用失败后如何继续」，不描述「是否撤销已发生的副作用」</b>：
 * 父 Run 失败<b>不得</b>被解释为所有已发起副作用均已撤销（07 变更补充）。
 * 已发出的外部副作用只能按 UNKNOWN 对账流程处置。
 */
public enum DelegationFailurePolicy {

    /**
     * 首个子调用失败即停止后续委派（缺省）。
     *
     * <p>V1 的保守默认：父 Agent 逐次委派时，后续子调用的输入通常依赖前一个的结果，
     * 前序失败时继续执行只会放大成本且必然失败。
     */
    FAIL_FAST,

    /**
     * 继续执行剩余子调用，失败结果照常回灌给父 Agent。
     *
     * <p>⚠️ 仅在子调用之间<b>无数据依赖</b>时才有意义。
     *
     * <p>⚠️ <b>口径澄清（评审前置决策 1 · 2026-10-25）</b>：本策略作用在
     * <b>同一轮</b>的多个工具调用之间 —— 某个委派失败后，是否继续执行本轮
     * 剩下的委派。失败结果<b>照常回灌</b>（工具结果回灌），
     * <b>不由框架聚合</b>；父 Agent 拿到这些结果后如何处置，是它自己的模型行为
     * （见 {@link OrchestrationMode#SEQUENTIAL}）。
     * ⚠️ 此前 javadoc 写的是「失败结果按输出契约聚合返回父 Agent」——
     * 框架<b>没有</b>这个动作，属不实承诺，已更正。
     */
    CONTINUE_ON_ERROR
}

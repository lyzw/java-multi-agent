package cn.studykid.multiagent.routing;

/**
 * 谓词求值的三值域（10 号设计 §2 的「求值失败语义必须冻结」）。
 *
 * <p>⚠️ <b>{@link #ERROR} 不是 {@link #FALSE} 的别名，也不参与「不成立」的短路</b>：
 * 布尔代数里把「不知道」折算成「假」是最省事的做法，而它的后果恰好是本方案要消灭的东西 ——
 * 一个字段名写错的条件会永久不成立，策略看起来在跑、实际全走兜底。
 * 三值是这里唯一的诚实表达：{@code TRUE} 命中、{@code FALSE} 不命中、
 * {@code ERROR} <b>表示这份策略在当前输入上无法判定</b>，必须留稳定码。
 */
public enum Truth {

    /** 成立。 */
    TRUE,

    /** 不成立。 */
    FALSE,

    /** 无法判定（缺失字段、类型不相容、正则输入非字符串等）。 */
    ERROR

}
